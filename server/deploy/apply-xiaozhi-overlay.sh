#!/usr/bin/env bash
# KidPal direction-B gateway: render the xiaozhi data/.config.yaml provider/auth overlay.
#
# Reads server/deploy/provider.config.yaml (frozen declarations) + server/deploy/secrets.env
# (credentials, chmod 600) and emits the official xiaozhi-esp32-server overlay file
# (/opt/kidpal/xiaozhi-esp32-server/deploy/xiaozhi-docker-data/.config.yaml). The overlay
# mechanism is upstream's documented way to override config.yaml without editing the
# repo file (secrets stay out of the clone; merges stay clean).
#
# Rendered pieces (matching actual xiaozhi config.yaml provider-block schema):
#   * server.auth.enabled = false (引擎层 auth 与 HMAC 动态签名机制绑死、与决策22 静态 token
#       不相容; token 强制在 front 层承载 — 260903 架构; 260911 human 裁 pod-events f9322b9c)
#   * selected_module.LLM = OpenClawOpenAI  -> type:openai, base_url 127.0.0.1:18789 (V28)
#       NO max_tokens in the streaming request (契约 §四 / V9 hard constraint)
#   * selected_module.TTS = EdgeTTS (edge zh-CN-XiaoxiaoNeural)
#   * selected_module.ASR = Qwen3ASRFlash (qwen3-asr-flash, DashScope 流式; human 2026-09-06 终选,
#       spec §A1 双候选之一). credentials injected from env (DASHSCOPE_API_KEY); if unset the
#       structural shape is still declared, live ASR is a known credential gap ->
#       escalate (human 待办). Never forged.
#
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
XSROOT="${XIAOZHI_ROOT:-/opt/kidpal/xiaozhi-esp32-server/deploy/xiaozhi-docker-data}"
DATA_DIR="$XSROOT"
OVERLAY="$DATA_DIR/.config.yaml"

# clip the device token from the secrets file if not in env.
# Device token: strong shared bearer token (决策22 >=22 chars). Empty => refuse to render.
DEVICE_TOKEN="${XIAOZHI_DEVICE_TOKEN:-}"
OPENCLAW_TOKEN="${OPENCLAW_TOKEN:-}"
DASHSCOPE_API_KEY="${DASHSCOPE_API_KEY:-}"
SECRETS="${XIAOZHI_SECRETS:-$HERE/secrets.env}"
if [ -f "$SECRETS" ]; then
  [ -z "$DEVICE_TOKEN" ]    && DEVICE_TOKEN="$(grep -E '^XIAOZHI_DEVICE_TOKEN=' "$SECRETS" | head -1 | cut -d= -f2- | tr -d '"' || true)"
  [ -z "$OPENCLAW_TOKEN" ]  && OPENCLAW_TOKEN="$(grep -E '^OPENCLAW_TOKEN=' "$SECRETS" | head -1 | cut -d= -f2- | tr -d '"' || true)"
  [ -z "$DASHSCOPE_API_KEY" ] && DASHSCOPE_API_KEY="$(grep -E '^DASHSCOPE_API_KEY=' "$SECRETS" | head -1 | cut -d= -f2- | tr -d '"' || true)"
fi

# device token present => render a secure overlay. token 未设 = 拒绝服务 (决策22/V11/V26).
if [ "${#DEVICE_TOKEN}" -lt 22 ]; then
  echo "ERR: device token unset/too short (<22). refusing to render auth-disabled config (决策22)" >&2
  exit 1
fi
# token 未设 = refuse-service (no validation-mode backdoor) is enforced by the gateway
# front that wraps this overlay; cron/systemd must set it before first boot.

mkdir -p "$DATA_DIR"
cat > "$OVERLAY" <<EOF
# generated by server/deploy/apply-xiaozhi-overlay.sh — DO NOT EDIT BY HAND.
# provider render source: server/deploy/provider.config.yaml. creds from server/deploy/secrets.env
server:
  auth:
    # 引擎层 auth 关：引擎 auth=HMAC 动态签名（core/auth.py AuthManager），与决策22 静态
    # 共享 token 不相容（front 层强制 token 已承载，260903 架构；260911 human 裁 pod-events f9322b9c）
    enabled: false
    allowed_devices: []   # 保留键形（引擎 auth 关；front 层承载 static shared bearer token 决策22）
  ip: 127.0.0.1
  port: 8010
selected_module:
  LLM: OpenClawOpenAI
  VLLM: OpenClawOpenAI
  TTS: EdgeTTS
  ASR: Qwen3ASRFlash     # DashScope 流式 (human 2026-09-06 终选; spec §A1 双候选之一)
  Memory: nomem
  Intent: nointent
LLM:
  OpenClawOpenAI:
    # type:openai 流式接 OpenClaw (决策18 / 契约 §四)
    type: openai
    base_url: http://127.0.0.1:18789/v1   # OpenClaw loopback (V28 18789 锁 127.0.0.1)
    model_name: openclaw/default
    api_key: "$OPENCLAW_TOKEN"
    # NOTE: stream 请求禁带 max_tokens (契约 §四 / V9) — enforced by provider.openclaw_stream_request
TTS:
  EdgeTTS:
    type: edge
    voice: zh-CN-XiaoxiaoNeural
ASR:
  Qwen3ASRFlash: {api_key: "$DASHSCOPE_API_KEY", model_name: qwen3-asr-flash, type: qwen3_asr_flash}
EOF
echo "rendered $OVERLAY"
ls -la "$OVERLAY"

# OpenClaw brain system prompt (VRT-E4 非孤儿接线): 渲染到 ECS data/ 与 .config.yaml 同目录 .
# 版本化文件 = live 探针 (VRT-A4/A7 / 包 C1 A8/A9) 的唯一 prompt 源, 保证「验收所测=生产所用」。
# 演进史 (历史版本文件一律不改、可 diff; 声明见 OPENCLAW_SYSTEM_PROMPT_CARRIER):
#   v1 = 260829-voice-roundtrip 基座 (两部分结构 + 7 view 白名单 + 三句纪律 + 硬约束)
#   v2 = openclaw-system-prompt.v2.md (260829-schedule-p2 + 260829-char-stroke: 课表 producer
#        扩展 + char C1 最小块/出口拼装)
#   v3 = openclaw-system-prompt.v3.md (两包并集版: 260829-story-p3 故事 producer 扩展 +
#        260829-schedule-reminder RMD-A8 包 7 提醒备注解析约定；两并行包各写一份 .v3 抢同槽位
#        (add/add)，按 human 授权 pod-events dc9a5c15 取并集；槽位预约规则见
#        ARQ-260908-versioned-artifact-slot-collision)。
#   v4 = openclaw-system-prompt.v4.md (260829-hardware-validation F4 分工修正:
#        删模型「回填整段正文」缺陷表述、改为一回合只起 title、story_text 正文+id 由网关下发;
#        v3 及其下 v1/v2 基座语义逐字保留、可 diff)。
#   v5 = openclaw-system-prompt.v5.md (当前渲染源; 260920-m2-charwindow-display-fix MCD-A5/A7:
#        char 最小意图块 data 增中文释义 meaning (同语音那句中文解释同源同字≤24字) + 面向设备
#        回复只含口语正文+一个 display 块、禁任何自检/来源/附录/明细/HTML 结构; v4 基座逐字保留)。
PROMPT_SRC="$HERE/openclaw-system-prompt.v5.md"
PROMPT_DST="$DATA_DIR/openclaw-system-prompt.v5.md"
if [ -f "$PROMPT_SRC" ]; then
  cp "$PROMPT_SRC" "$PROMPT_DST"
  echo "rendered openclaw-system-prompt -> $PROMPT_DST"
  # 将全部 prompt 作为顶层 `prompt: |` literal block 注入 .config.yaml (替代 base config.yaml
  # 第 203 行小智默认台湾腔人设)。prompt 是顶层键 (merge_configs deep-merge 覆盖、connection.py
  # 以 config["prompt"] 取用)。markdown 含反引号, 不能放进上面未加引号的 <<EOF, 故在此追加。
  # 注: 只在 .config.yaml 不存在 prompt 键时注入, 避免重复渲染叠加。
  if ! grep -q '^prompt:' "$OVERLAY" 2>/dev/null; then
    {
      printf '\nprompt: |\n'
      sed 's/^/  /' "$PROMPT_SRC"
    } >> "$OVERLAY"
    echo "rendered prompt: literal block -> $OVERLAY"
  else
    echo "SKIP prompt injection: $OVERLAY already has a 'prompt:' key"
  fi
else
  echo "WARN: openclaw-system-prompt.v5.md not found at $PROMPT_SRC — E4 接线缺失, 请检查 server/deploy/" >&2
fi

# 提醒三档阶梯配置 (260829-schedule-reminder / RMD-A2): 三档时刻的家 = 纯服务端配置,
# 随本 overlay 一起上 ECS，由 OpenClaw cron 载荷脚本
# (openclaw-patch/reminder_schedule_lib.py::load_ladder_config) 读取。改时刻即时生效、
# 永不需烧板子（固件侧零引用 = C 孪生档 RMD-A7 齿负向钉死；不进契约 B1）。
# 缺文件不停摆（脚本回退 DEFAULT_LADDER_CONFIG），但「落盘 ≠ 孤儿」——本行渲染即接线。
REMINDER_CFG="$HERE/openclaw-reminder.config.yaml"
if [ -f "$REMINDER_CFG" ]; then
  cp "$REMINDER_CFG" "$DATA_DIR/openclaw-reminder.config.yaml"
  echo "rendered openclaw-reminder.config.yaml -> $DATA_DIR/"
  # 提醒排程脚本随 openclaw-patch 一起铺到 OpenClaw 侧可读目录，供 cron --command 调用。
  # 路径全部 env 可配（KIDPAL_ALERTS_DIR / KIDPAL_PENDING_JSON / KIDPAL_SEMANTIC_JSON /
  # KIDPAL_REMINDER_CONFIG / KIDPAL_SERVER_DIR）—— 禁止硬编 /root/.openclaw/**。
  for script in reminder_schedule_lib.py; do
    if [ -f "$HERE/openclaw-patch/$script" ]; then
      mkdir -p "${KIDPAL_OPENCLAW_SCRIPT_DIR:-$DATA_DIR/openclaw-patch}"
      cp "$HERE/openclaw-patch/$script" "${KIDPAL_OPENCLAW_SCRIPT_DIR:-$DATA_DIR/openclaw-patch}/$script"
      echo "staged $script -> ${KIDPAL_OPENCLAW_SCRIPT_DIR:-$DATA_DIR/openclaw-patch}/"
    fi
  done
else
  echo "WARN: openclaw-reminder.config.yaml not found at $REMINDER_CFG — 三档时刻没有渲染面 (RMD-A2)" >&2
fi